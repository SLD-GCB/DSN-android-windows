<#
  一键出「可分发」的 release 包。

  - Android：**已签名**的 release APK。首次运行会自动生成 keystore（强随机口令）、
    写好 keystore.properties 并把口令打印一次，之后每次复用同一密钥；
    打包后会用 apksigner 校验签名，没签上直接失败退出。
  - Windows：PyInstaller onedir 压缩包。

  产物：dist\release\DSN-android-<版本>.apk
        dist\release\DSN-windows-<版本>.zip

  用法：
    powershell -ExecutionPolicy Bypass -File scripts\build_release.ps1
    powershell -ExecutionPolicy Bypass -File scripts\build_release.ps1 -SkipWin -Offline
    powershell -ExecutionPolicy Bypass -File scripts\build_release.ps1 -Version 0.2.0
#>
[CmdletBinding()]
param(
    [switch]$SkipAndroid,
    [switch]$SkipWin,
    [switch]$Offline,
    [switch]$Clean,
    [string]$Version = ""
)

$ErrorActionPreference = "Stop"
[Console]::OutputEncoding = [Text.Encoding]::UTF8

$RepoRoot    = Split-Path -Parent $PSScriptRoot
$AndroidDir  = Join-Path $RepoRoot "大司农-android"
$KeyDir      = Join-Path $AndroidDir "keystore"
$JksPath     = Join-Path $KeyDir "dasinong-release.jks"
$PropsPath   = Join-Path $AndroidDir "keystore.properties"
$PwBackup    = Join-Path $KeyDir "PASSWORD-BACKUP.txt"
$DistRelease = Join-Path $RepoRoot "dist\release"

function Step($msg) { Write-Host "`n==> $msg" -ForegroundColor Cyan }
function Fail($msg) { Write-Host "`n!! $msg" -ForegroundColor Red; exit 1 }

# 用「无 BOM 的 UTF-8」写文本：java.util.Properties 读 InputStream 时不认 BOM，
# 带 BOM 会把第一个键名前多出 \uFEFF，导致 storeFile 取不到值。
function Write-NoBom($path, $text) {
    [System.IO.File]::WriteAllText($path, $text, (New-Object System.Text.UTF8Encoding($false)))
}

# ---------------------------------------------------------------- 环境
if (-not $env:JAVA_HOME) {
    $jbr = Get-ChildItem (Join-Path $env:USERPROFILE ".jdks") -Directory -Filter "jbr-*" -ErrorAction SilentlyContinue |
        Sort-Object Name -Descending | Select-Object -First 1
    if ($jbr) { $env:JAVA_HOME = $jbr.FullName }
}
if (-not $env:JAVA_HOME) {
    $javaCmd = Get-Command java -ErrorAction SilentlyContinue
    if ($javaCmd) { $env:JAVA_HOME = Split-Path -Parent (Split-Path -Parent $javaCmd.Source) }
}
if (-not $env:JAVA_HOME) { Fail "未找到 JDK，请设置 JAVA_HOME（需要 JDK 17+）" }
if (-not $env:ANDROID_HOME -and -not $env:ANDROID_SDK_ROOT) {
    $sdk = Join-Path $env:LOCALAPPDATA "Android\Sdk"
    if (Test-Path $sdk) { $env:ANDROID_HOME = $sdk }
}
$Keytool = Join-Path $env:JAVA_HOME "bin\keytool.exe"
if (-not (Test-Path $Keytool)) { Fail "找不到 keytool：$Keytool" }

# ---------------------------------------------------------------- 版本号
if (-not $Version) {
    $gradleFile = Join-Path $AndroidDir "UI\build.gradle.kts"
    $m = [regex]::Match((Get-Content $gradleFile -Raw), 'versionName\s*=\s*"([^"]+)"')
    $Version = if ($m.Success) { $m.Groups[1].Value } else { "0.0.0" }
}
Write-Host "版本：$Version"

# ---------------------------------------------------------------- 密钥
function New-StrongPassword([int]$len = 32) {
    # 只用字母数字：避免 properties / 命令行引号被特殊字符搞坏
    $chars = ([char[]](48..57)) + ([char[]](65..90)) + ([char[]](97..122))
    -join (1..$len | ForEach-Object { $chars | Get-Random })
}

$FreshPw = $null
if (-not (Test-Path $PropsPath) -or -not (Test-Path $JksPath)) {
    Step "首次打包：生成签名密钥（请务必按提示备份）"
    New-Item -ItemType Directory -Force -Path $KeyDir | Out-Null
    $pw = New-StrongPassword 32
    & $Keytool -genkeypair -v -keystore $JksPath -alias dasinong `
        -keyalg RSA -keysize 4096 -validity 10000 -storetype PKCS12 `
        -storepass $pw -keypass $pw -dname "CN=Dasinong,O=Dasinong,C=CN"
    if ($LASTEXITCODE -ne 0 -or -not (Test-Path $JksPath)) { Fail "keytool 生成密钥失败" }

    $props = @(
        "# generated by scripts/build_release.ps1 - DO NOT COMMIT",
        "storeFile=keystore/dasinong-release.jks",
        "storePassword=$pw",
        "keyAlias=dasinong",
        "keyPassword=$pw"
    ) -join "`n"
    Write-NoBom $PropsPath ($props + "`n")
    $backup = @(
        "大司农 release 签名密钥备份",
        "",
        "keystore : $JksPath",
        "alias    : dasinong",
        "口令     : $pw",
        "",
        "⚠ 这个 keystore 决定了 APK 的签名，丢了就无法再覆盖安装以后发布的版本（只能卸载重装）。",
        "⚠ 不要提交到代码仓库；请抄进密码管理器或离线保存。"
    ) -join "`n"
    Write-NoBom $PwBackup ($backup + "`n")
    $FreshPw = $pw
} else {
    Step "复用已有签名密钥（$JksPath）"
}

# ---------------------------------------------------------------- Android
$ApkPath = $null
if (-not $SkipAndroid) {
    Step "构建 Android release（签名）"
    # 用哈希表 splat：数组 splat 到 [CmdletBinding()] 脚本会被当成位置参数而报错
    $androidParams = @{ Release = $true }
    if ($Offline) { $androidParams.Offline = $true }
    if ($Clean)   { $androidParams.Clean = $true }
    & (Join-Path $PSScriptRoot "build_android.ps1") @androidParams
    if ($LASTEXITCODE -ne 0) { Fail "build_android.ps1 -Release 失败" }

    $apkDir = Join-Path $AndroidDir "UI\build\outputs\apk\release"
    $apks = Get-ChildItem $apkDir -Filter "*.apk" -ErrorAction SilentlyContinue |
        Where-Object { $_.Name -notmatch "unsigned" }
    if (-not $apks) { Fail "没找到已签名的 release APK：$apkDir" }
    $ApkPath = ($apks | Sort-Object LastWriteTime -Descending | Select-Object -First 1).FullName

    Step "校验签名"
    $apksigner = $null
    $bt = Join-Path $env:ANDROID_HOME "build-tools"
    if (Test-Path $bt) {
        $apksigner = Get-ChildItem $bt -Directory -ErrorAction SilentlyContinue |
            Where-Object { $_.Name -match '^\d+(\.\d+)+$' } |
            Sort-Object { [version]$_.Name } -Descending |
            ForEach-Object { Join-Path $_.FullName "apksigner.bat" } |
            Where-Object { Test-Path $_ } | Select-Object -First 1
    }
    $certs = ""
    $signed = $false
    if ($apksigner) {
        # 注意：不要对原生命令用 2>&1（$ErrorActionPreference=Stop 下 stderr 会被当成终止错误）
        $certs = (& $apksigner verify --print-certs $ApkPath | Out-String)
        $signed = ($LASTEXITCODE -eq 0)
    }
    if (-not $signed) {
        # 回退：我们开了 v1 签名，keytool 也能读出来
        $certs = (& $Keytool -printcert -jarfile $ApkPath | Out-String)
        $signed = ($LASTEXITCODE -eq 0)
    }
    if (-not $signed) { Fail "APK 未通过签名校验，产物不可用。`n$certs" }
    Write-Host "签名校验通过 ✓" -ForegroundColor Green
    ($certs -split "`n") | Where-Object { $_ -match "SHA256|SHA-256|证书指纹|Certificate fingerprints" } |
        Select-Object -First 2 | ForEach-Object { Write-Host ("  " + $_.Trim()) }
}

# ---------------------------------------------------------------- Windows
$ZipPath = $null
if (-not $SkipWin) {
    Step "构建 Windows（PyInstaller onedir）"
    $winParams = @{}
    if ($Clean) { $winParams.Clean = $true }
    & (Join-Path $PSScriptRoot "build_win.ps1") @winParams
    if ($LASTEXITCODE -ne 0) { Fail "build_win.ps1 失败" }
    $ZipPath = Join-Path $RepoRoot "dist\大司农-windows.zip"
    if (-not (Test-Path $ZipPath)) { Fail "没找到 Windows 压缩包：$ZipPath" }
}

# ---------------------------------------------------------------- 收集
# 对外分发的产物统一用 DSN- 前缀（与开源仓库名 DSN-android-windows 对齐）
Step "收集产物到 dist\release"
New-Item -ItemType Directory -Force -Path $DistRelease | Out-Null
if ($ApkPath) {
    $dst = Join-Path $DistRelease "DSN-android-$Version.apk"
    Copy-Item $ApkPath $dst -Force
    Write-Host "  $dst" -ForegroundColor Green
}
if ($ZipPath) {
    $dst = Join-Path $DistRelease "DSN-windows-$Version.zip"
    Copy-Item $ZipPath $dst -Force
    Write-Host "  $dst" -ForegroundColor Green
}

if ($FreshPw) {
    Write-Host ""
    Write-Host "================= 请立即备份签名口令（只显示这一次） =================" -ForegroundColor Yellow
    Write-Host "  keystore : $JksPath"
    Write-Host "  alias    : dasinong"
    Write-Host "  口令     : $FreshPw" -ForegroundColor Yellow
    Write-Host "  备份文件 : $PwBackup"
    Write-Host "  ⚠ 丢了它就没法再覆盖安装以后发布的版本；也千万别提交到仓库。" -ForegroundColor Yellow
    Write-Host "===================================================================" -ForegroundColor Yellow
}

Step "完成"
exit 0
